typedef StudentModel = StudentProfile;

class StudentProfile {
  const StudentProfile({
    required this.number,
    required this.name,
    required this.age,
    required this.attendanceNumber,
    required this.hobby,
    required this.birthPlaceAndDate,
    required this.photoPath,
  });

  final int number;
  final String name;
  final String age;
  final String attendanceNumber;
  final String hobby;
  final String birthPlaceAndDate;
  final String photoPath;

  Map<String, dynamic> toJson() => {
    'number': number,
    'name': name,
    'age': age,
    'attendanceNumber': attendanceNumber,
    'hobby': hobby,
    'birthPlaceAndDate': birthPlaceAndDate,
    'photoPath': photoPath,
  };

  factory StudentProfile.fromJson(Map<String, dynamic> json) => StudentProfile(
    number: json['number'] as int,
    name: json['name'] as String? ?? '',
    age: json['age'] as String? ?? '',
    attendanceNumber: json['attendanceNumber'] as String? ?? '',
    hobby: json['hobby'] as String? ?? '',
    birthPlaceAndDate: json['birthPlaceAndDate'] as String? ?? '',
    photoPath: json['photoPath'] as String? ?? '',
  );

  StudentProfile copyWith({
    String? name,
    String? age,
    String? hobby,
    String? birthPlaceAndDate,
  }) => StudentProfile(
    number: number,
    name: name ?? this.name,
    age: age ?? this.age,
    attendanceNumber: attendanceNumber,
    hobby: hobby ?? this.hobby,
    birthPlaceAndDate: birthPlaceAndDate ?? this.birthPlaceAndDate,
    photoPath: photoPath,
  );

  String get displayName {
    if (name.isNotEmpty) {
      return name;
    }
    return 'Siswa ${number.toString().padLeft(2, '0')}';
  }
}

